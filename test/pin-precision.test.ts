import { mkdir, mkdtemp, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { describe, expect, it } from "vitest";
import { scanRepo } from "../src/scan/index.js";

const repo = async (files: Record<string, string>) => {
  const d = await mkdtemp(join(tmpdir(), "vitasta-pinprec-"));
  for (const [p, t] of Object.entries(files)) {
    await mkdir(dirname(join(d, p)), { recursive: true });
    await writeFile(join(d, p), t);
  }
  return d;
};

describe("version pins: generated files and version lists", () => {
  it("an enum listing Graph versions is a catalog; a generated file's pins are dropped", async () => {
    const us = (await scanRepo(await repo({
      "src/graph.ts": "// graph.facebook.com versions this SDK knows\nexport enum GraphVersion {\n  V18 = \"v18.0\",\n  V21 = \"v21.0\",\n}\n",
      "src/Models/Page.generated.cs": "// <auto-generated>\n//   This code was generated by a tool.\n// </auto-generated>\nnamespace Acme {\n  /// Graph API v19.0 page, from https://graph.facebook.com/v19.0/{page-id}\n  public partial class Page { public const string ApiVersion = \"v19.0\"; }\n}\n",
    }))).usages.filter((u: any) => u.kind === "version-pin");
    const enumPins = us.filter((u: any) => u.file === "src/graph.ts");
    expect(enumPins.length).toBeGreaterThan(0);
    expect(enumPins.every((u: any) => u.role === "catalog")).toBe(true);
    expect(us.filter((u: any) => u.file.endsWith(".generated.cs"))).toEqual([]);
  });
});
