# Microsoft.Extensions.AI adapters: which ChatOptions settings a provider SDK's IChatClient adapter sends, read from the
# published DLLs (never loaded or run). For each provider release: the extension methods that return
# Microsoft.Extensions.AI.IChatClient (AsIChatClient), and, in the adapter's method bodies, each ChatOptions getter
# paired with the provider params setter of the same setting (Temperature -> Temperature, ModelId -> Model,
# MaxOutputTokens -> MaxTokens). Wire names come from the provider's own vocabulary file (its params type's fields).
#
# Usage: python3 -I gen_meai.py <meai Abstractions dll> <meai version> <provider vocab json> <out json>
#        <provider version>=<provider dll> ...
import json, sys, os, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cil import Reader

abs_dll, meai_ver, vocab_p, out_p, *rels = sys.argv[1:]
vocab = json.load(open(vocab_p))
meai = Reader(open(abs_dll, "rb").read())
opts = next(t for t in meai.types() if t["name"] == "Microsoft.Extensions.AI.ChatOptions")
opt_props = {p["name"] for p in opts["props"]}

def norm(s): return re.sub(r"(Id|Output)", "", s).lower()

fields, adapters, versions, ops = {}, set(), [], set()
for rel in rels:
    ver, dll = rel.split("=", 1)
    r = Reader(open(dll, "rb").read())
    types = r.types()
    ext = [(t, m) for t in types for m in t["methods"] if m["static"] and m["ret"] == "Microsoft.Extensions.AI.IChatClient"]
    if not ext: continue
    versions.append(ver)
    roots = {t["name"] for t, _ in ext}
    for _, m in ext: adapters.add(m["name"])
    for t in types:
        if not any(t["name"] == x or t["name"].startswith(x + "+") for x in roots): continue
        for m in t["methods"]:
            if not m.get("rva"): continue
            calls = r.calls(m["rva"])
            gets = {n[4:] for (ty, n) in calls if ty == "Microsoft.Extensions.AI.ChatOptions" and n.startswith("get_") and n[4:] in opt_props}
            sets = {(ty, n[4:]) for (ty, n) in calls if n.startswith("set_") and ty in vocab["paramTypes"]}
            for g in gets:
                for ty, s in sets:
                    if norm(s) == norm(g):
                        wire = vocab["paramTypes"][ty]["fields"].get(s)
                        if wire:
                            fields[g] = wire
                            ops.update(vocab["paramTypes"][ty].get("ops") or [])

out = {
    "_about": f"Microsoft.Extensions.AI ChatOptions as sent by {vocab['package']} ({vocab['registry']})'s IChatClient adapter, generated by tools/vocab/gen_meai.py from the published packages, each .nupkg checked against NuGet's catalog SHA-512 (never installed or run). Don't edit by hand.",
    "lang": "cs", "registry": "nuget", "package": vocab["package"], "provider": vocab["provider"],
    "versions": versions, "namespaces": ["Microsoft.Extensions.AI"],
    "adapter": {"package": "Microsoft.Extensions.AI.Abstractions", "packageVersions": [meai_ver], "methods": sorted(adapters)},
    "paramTypes": {"Microsoft.Extensions.AI.ChatOptions": {"fields": dict(sorted(fields.items())), "ops": sorted(ops), "versions": versions}} if fields else {},
    "types": {}, "clients": {},
}
json.dump(out, open(out_p, "w"), indent=1, sort_keys=False)
print(out_p, versions, out["adapter"]["methods"], out["paramTypes"])
